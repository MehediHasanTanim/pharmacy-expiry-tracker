/// Lower-cases, strips common Latin diacritics, and collapses whitespace, so
/// "  Paracétamol   500MG " matches "paracetamol 500mg".
String normalizeSearchText(String input) {
  final lower = input.toLowerCase();
  final buf = StringBuffer();
  for (final rune in lower.runes) {
    final ch = String.fromCharCode(rune);
    buf.write(_diacritics[ch] ?? ch);
  }
  return buf.toString().trim().replaceAll(RegExp(r'\s+'), ' ');
}

/// Batch numbers are compared upper-case with surrounding space removed.
